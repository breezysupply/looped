/* Embeds the Terraform + AWS tech-screen lab package
   (labs/terraform-aws-tech-screen) into assets/js/data/tfs-src.js, so the app
   shows exactly the files validate-all.sh checks with the real terraform CLI.

   node tools/tfs-src.js           regenerate
   node tools/tfs-src.js --check   exit 1 if the embedded copy is stale */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PKG = path.join(ROOT, 'labs', 'terraform-aws-tech-screen');
const OUT = path.join(ROOT, 'assets', 'js', 'data', 'tfs-src.js');

function collect() {
  const out = {};
  fs.readdirSync(PKG).filter(d => !d.startsWith('.') && fs.statSync(path.join(PKG, d)).isDirectory()).sort().forEach(function (lab) {
    fs.readdirSync(path.join(PKG, lab)).sort().forEach(function (sub) {
      const dir = path.join(PKG, lab, sub);
      if (!fs.statSync(dir).isDirectory() || sub.startsWith('.')) return;
      const files = fs.readdirSync(dir).filter(f => /\.tf$/.test(f)).sort();
      if (!files.length) return;
      out[lab + '/' + sub] = {};
      files.forEach(f => { out[lab + '/' + sub][f] = fs.readFileSync(path.join(dir, f), 'utf8'); });
    });
  });
  return out;
}

const src = collect();
const text = '/* GENERATED by tools/tfs-src.js from labs/terraform-aws-tech-screen — do not edit.\n' +
  '   References and alternatives passed terraform fmt -check, init -backend=false and\n' +
  '   validate when the package was last checked (see its README). Starters are\n' +
  '   intentionally incomplete. */\n' +
  'window.LX = window.LX || { commands: [], scenarios: [], drills: [] };\n' +
  'LX.tfsSrc = ' + JSON.stringify(src, null, 1) + ';\n';
if (process.argv.indexOf('--check') !== -1) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== text) { console.error('assets/js/data/tfs-src.js is stale: run node tools/tfs-src.js'); process.exit(1); }
  console.log('tfs-src.js is current');
} else {
  fs.writeFileSync(OUT, text);
  console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + Object.keys(src).length + ' file sets)');
}
