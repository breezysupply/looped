/* Embeds the Anduril Round 1 Terraform package (labs/anduril-round1/terraform)
   into assets/js/data/ar1-tf-src.js so the app shows exactly the files that
   `validate-all.sh` checks with the real terraform CLI. One source of truth.

   node tools/ar1-tf-src.js           regenerate
   node tools/ar1-tf-src.js --check   exit 1 if the embedded copy is stale */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PKG = path.join(ROOT, 'labs', 'anduril-round1', 'terraform');
const OUT = path.join(ROOT, 'assets', 'js', 'data', 'ar1-tf-src.js');

function collect() {
  const out = {};
  fs.readdirSync(PKG).filter(d => /^(T\d|M[A-Z]-)/.test(d)).sort().forEach(function (lab) {
    const id = lab.split('-')[0];
    (function walk(dir, rel) {
      const files = fs.readdirSync(dir).sort();
      const tf = files.filter(f => /\.(tf|sh)$/.test(f) && fs.statSync(path.join(dir, f)).isFile());
      if (tf.length && rel) {
        out[id + '/' + rel] = {};
        tf.forEach(f => { out[id + '/' + rel][f] = fs.readFileSync(path.join(dir, f), 'utf8'); });
      }
      files.forEach(f => { const p = path.join(dir, f); if (fs.statSync(p).isDirectory() && f[0] !== '.') walk(p, rel ? rel + '/' + f : f); });
    })(path.join(PKG, lab), '');
  });
  return out;
}

function render(src) {
  return '/* GENERATED by tools/ar1-tf-src.js from labs/anduril-round1/terraform — do not edit.\n' +
    '   Every configuration here passed `terraform fmt -check`, `init -backend=false`\n' +
    '   and `validate` when the package was last checked (see that README). */\n' +
    'window.LX = window.LX || { commands: [], scenarios: [], drills: [] };\n' +
    'LX.ar1TfSrc = ' + JSON.stringify(src, null, 1) + ';\n';
}

const text = render(collect());
if (process.argv.indexOf('--check') !== -1) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== text) { console.error('assets/js/data/ar1-tf-src.js is stale: run node tools/ar1-tf-src.js'); process.exit(1); }
  console.log('ar1-tf-src.js is current');
} else {
  fs.writeFileSync(OUT, text);
  console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + Object.keys(collect()).length + ' configurations)');
}
